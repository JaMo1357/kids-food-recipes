// Generates supabase/seed.sql from data/. The output is idempotent: run it
// against any database to bring the catalog in line with data/ without touching
// user data. Fails on anything that could hide an allergen.
import { writeFileSync } from 'node:fs'
import { allergens, ingredients, tags } from '../data/ingredients.mjs'
import { recipes } from '../data/recipes.mjs'

const allergenCodes = new Set(allergens.map(([code]) => code))
const bySlug = new Map()
const errors = []

for (const ingredient of ingredients) {
  if (bySlug.has(ingredient.slug)) errors.push(`Duplicate ingredient ${ingredient.slug}`)
  if (!Array.isArray(ingredient.allergens)) errors.push(`${ingredient.slug}: allergens missing`)
  if (ingredient.parent && !bySlug.has(ingredient.parent)) {
    errors.push(`${ingredient.slug}: parent ${ingredient.parent} must be defined before it`)
  }
  for (const code of ingredient.allergens ?? []) {
    if (!allergenCodes.has(code)) errors.push(`${ingredient.slug}: unknown allergen ${code}`)
  }
  bySlug.set(ingredient.slug, ingredient)
}

const tagSlugs = new Set(tags.map(([slug]) => slug))
const recipeSlugs = new Set()
for (const recipe of recipes) {
  if (recipeSlugs.has(recipe.slug)) errors.push(`Duplicate recipe ${recipe.slug}`)
  recipeSlugs.add(recipe.slug)
  const seen = new Set()
  for (const [slug] of recipe.ingredients) {
    const ingredient = bySlug.get(slug)
    if (!ingredient) errors.push(`${recipe.slug}: unknown ingredient ${slug}`)
    else if (ingredient.group) errors.push(`${recipe.slug}: ${slug} is a group`)
    if (seen.has(slug)) errors.push(`${recipe.slug}: ${slug} listed twice`)
    seen.add(slug)
  }
  for (const tag of recipe.tags) {
    if (!tagSlugs.has(tag)) errors.push(`${recipe.slug}: unknown tag ${tag}`)
  }
}

if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}

const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replaceAll("'", "''")}'`)
const num = (value) => value ?? 'null'
const lines = ['-- Generated by scripts/build-seed.mjs from data/. Do not edit by hand.', 'begin;', '']

for (const [code, number, name, emoji] of allergens) {
  lines.push(`insert into public.allergens (code, eu_number, name_cs, emoji) values (${q(code)}, ${number}, ${q(name)}, ${q(emoji)})
  on conflict (code) do update set eu_number = excluded.eu_number, name_cs = excluded.name_cs, emoji = excluded.emoji;`)
}
for (const [slug, kind, name, order] of tags) {
  lines.push(`insert into public.tags (slug, kind, name_cs, sort_order) values (${q(slug)}, ${q(kind)}, ${q(name)}, ${order})
  on conflict (slug) do update set kind = excluded.kind, name_cs = excluded.name_cs, sort_order = excluded.sort_order;`)
}

for (const i of ingredients) {
  const parent = i.parent ? `(select id from public.ingredients where slug = ${q(i.parent)})` : 'null'
  lines.push(`insert into public.ingredients (slug, name_cs, parent_id, is_group, min_age_months, age_note)
  values (${q(i.slug)}, ${q(i.name)}, ${parent}, ${i.group === true}, ${i.minAge ?? 0}, ${q(i.ageNote)})
  on conflict (slug) do update set name_cs = excluded.name_cs, parent_id = excluded.parent_id,
    is_group = excluded.is_group, min_age_months = excluded.min_age_months, age_note = excluded.age_note;`)
  lines.push(`delete from public.ingredient_allergens where ingredient_id = (select id from public.ingredients where slug = ${q(i.slug)});`)
  for (const code of i.allergens) {
    lines.push(`insert into public.ingredient_allergens (ingredient_id, allergen_code)
  values ((select id from public.ingredients where slug = ${q(i.slug)}), ${q(code)});`)
  }
}

for (const r of recipes) {
  const steps = `array[${r.steps.map(q).join(', ')}]::text[]`
  lines.push(`insert into public.recipes (slug, title, description, min_age_months, max_age_months, prep_minutes, servings, steps, tip, illustration, source_name, source_url, is_published)
  values (${q(r.slug)}, ${q(r.title)}, ${q(r.description)}, ${r.minAge}, ${num(r.maxAge)}, ${r.minutes}, ${q(r.servings)}, ${steps}, ${q(r.tip)}, ${q(r.illustration)}, ${q(r.sourceName)}, ${q(r.sourceUrl)}, true)
  on conflict (slug) do update set title = excluded.title, description = excluded.description,
    min_age_months = excluded.min_age_months, max_age_months = excluded.max_age_months,
    prep_minutes = excluded.prep_minutes, servings = excluded.servings, steps = excluded.steps,
    tip = excluded.tip, illustration = excluded.illustration, source_name = excluded.source_name,
    source_url = excluded.source_url, is_published = true, updated_at = now();`)
  const id = `(select id from public.recipes where slug = ${q(r.slug)})`
  lines.push(`delete from public.recipe_ingredients where recipe_id = ${id};`)
  lines.push(`delete from public.recipe_tags where recipe_id = ${id};`)
  r.ingredients.forEach(([slug, amount, unit, note, optional], index) => {
    lines.push(`insert into public.recipe_ingredients (recipe_id, ingredient_id, position, amount, unit, note, is_optional)
  values (${id}, (select id from public.ingredients where slug = ${q(slug)}), ${index}, ${num(amount)}, ${q(unit)}, ${q(note)}, ${optional === true});`)
  })
  for (const tag of r.tags) {
    lines.push(`insert into public.recipe_tags (recipe_id, tag_slug) values (${id}, ${q(tag)});`)
  }
}

// Recipes removed from data/ are hidden, not deleted, so favorites survive.
lines.push(`update public.recipes set is_published = false where slug not in (${recipes.map((r) => q(r.slug)).join(', ')});`)
lines.push('', 'commit;', '')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n'))
console.log(`Wrote ${recipes.length} recipes and ${ingredients.length} ingredients to supabase/seed.sql`)
